/**
 * horseNames.js
 * ------------------------------------------------------------
 * 馬名の生成を担当するモジュール。
 * 「接頭語」×「接尾語」の組み合わせで100種類以上の馬名を作り出す。
 * 接頭語・接尾語の配列に単語を追加するだけで馬名のバリエーションが
 * 増えるため、後から簡単に拡張できる。
 * ------------------------------------------------------------
 */

const HorseNames = (() => {
  // 接頭語（イメージ・色・属性など）
  const PREFIXES = [
    'サンダー', 'ブラック', 'ゴールド', 'ナイト', 'クリムゾン', 'シルバー',
    'ホワイト', 'レッド', 'ブルー', 'グリーン', 'スカイ', 'ムーン',
    'サン', 'スター', 'ドラゴン', 'フェニックス', 'ライトニング', 'ストーム',
    'ミラクル', 'ロイヤル', 'インペリアル', 'グランド', 'スーパー', 'ハイパー',
    'ウルトラ', 'エース', 'キング', 'クイーン', 'プリンス', 'デューク',
    'バロン', 'ヒーロー', 'レジェンド', 'マイティ', 'スウィフト', 'ブレイブ',
    'グローリー', 'ヴィクトリー', 'トライアンフ', 'コズミック', 'ギャラクシー',
    'クリスタル', 'ダイヤモンド', 'エメラルド', 'サファイア', 'ルビー',
    'フレイム', 'ブレイズ', 'アイス', 'フロスト', 'テンペスト',
  ];

  // 接尾語（動物・自然物・概念など）
  const SUFFIXES = [
    'ボルト', 'フェザー', 'ウイング', 'ランナー', 'スター', 'ロード',
    'ホーク', 'イーグル', 'ウルフ', 'ライオン', 'タイガー', 'ドラゴン',
    'フェニックス', 'コメット', 'ミサイル', 'アロー', 'ブレット', 'ソード',
    'シールド', 'クラウン', 'フレイム', 'ブレイズ', 'スパーク', 'サンダー',
    'ストーム', 'ウェーブ', 'タイフーン', 'ノヴァ', 'メテオ', 'スピリット',
    'ソウル', 'ハート', 'ドリーム', 'ホープ', 'ミラクル', 'グローリー',
    'ヴィクトリー', 'チャンピオン', 'マスター', 'エンペラー', 'ジェネラル',
    'ナイト', 'デューク', 'バロン', 'ロード', 'ギャラクシー', 'レジェンド',
    'ジャスティス', 'フォース', 'スピード',
  ];

  /**
   * 全ての組み合わせ（接頭語×接尾語）を生成する。
   * 重複しやすい組（例:「ドラゴンドラゴン」）は除外する。
   */
  function buildAllNames() {
    const names = [];
    for (const prefix of PREFIXES) {
      for (const suffix of SUFFIXES) {
        if (prefix === suffix) continue;
        names.push(`${prefix}${suffix}`);
      }
    }
    return names;
  }

  const ALL_NAMES = buildAllNames();

  /**
   * 重複しないランダムな馬名を count 頭分取得する。
   */
  function pickRandomNames(count) {
    const pool = [...ALL_NAMES];
    const picked = [];
    for (let i = 0; i < count; i++) {
      const index = Math.floor(Math.random() * pool.length);
      picked.push(pool[index]);
      pool.splice(index, 1);
    }
    return picked;
  }

  return {
    ALL_NAMES,
    pickRandomNames,
  };
})();
